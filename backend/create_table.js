import 'dotenv/config';
import pg from 'pg';

const { Client } = pg;

const client = new Client({
  host: process.env.POSTGRES_HOST,
  port: Number(process.env.POSTGRES_PORT),
  database: process.env.POSTGRES_DB,
  user: process.env.POSTGRES_USER,
  password: process.env.POSTGRES_PASSWORD,
  ssl: process.env.POSTGRES_SSL === 'true' ? { rejectUnauthorized: false } : false,
  connectionTimeoutMillis: 15000,
});

const ddl = `
CREATE TABLE IF NOT EXISTS mandi.verification_results (
    verification_id  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    market_price_id  BIGINT NOT NULL REFERENCES mandi.market_prices(market_price_id),
    status           VARCHAR(20) NOT NULL,
    field_results    TEXT,
    issue_type       VARCHAR(50),
    expected_value   VARCHAR(200),
    scraped_value    VARCHAR(200),
    notes            TEXT,
    verified_by      VARCHAR(100),
    verified_at      TIMESTAMP NOT NULL DEFAULT (now() AT TIME ZONE 'utc')
);
`;

const indexDdl = `
CREATE INDEX IF NOT EXISTS idx_verification_results_market_price_id
    ON mandi.verification_results (market_price_id, verified_at DESC);
`;

try {
  await client.connect();
  await client.query(ddl);
  await client.query(indexDdl);
  console.log('mandi.verification_results table ready.');
  await client.end();
  process.exit(0);
} catch (err) {
  console.error('FAILED:', err.message);
  process.exit(1);
}
