import 'dotenv/config';
import pg from 'pg';

const { Client } = pg;

const client = new Client({
  host: process.env.POSTGRES_HOST,
  port: Number(process.env.POSTGRES_PORT),
  database: process.env.POSTGRES_DB,
  user: process.env.POSTGRES_USER,
  password: process.env.POSTGRES_PASSWORD,
  ssl: process.env.POSTGRES_SSL === 'true' ? { rejectUnauthorized: false } : false,
  connectionTimeoutMillis: 15000,
});

// Named dashboard_users, not users — this same Postgres server hosts other,
// unrelated projects (see newdb/public schemas) with their own users-ish
// tables. Do not rename/reuse those.
const ddl = `
CREATE TABLE IF NOT EXISTS mandi.dashboard_users (
    user_id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name           VARCHAR(200) NOT NULL,
    email          VARCHAR(256) NOT NULL UNIQUE,
    password_hash  VARCHAR(200) NOT NULL,
    role           VARCHAR(50) NOT NULL DEFAULT 'QA Tester',
    created_at     TIMESTAMP NOT NULL DEFAULT (now() AT TIME ZONE 'utc')
);
`;

try {
  await client.connect();
  await client.query(ddl);
  console.log('mandi.dashboard_users table ready.');
  await client.end();
  process.exit(0);
} catch (err) {
  console.error('FAILED:', err.message);
  process.exit(1);
}
