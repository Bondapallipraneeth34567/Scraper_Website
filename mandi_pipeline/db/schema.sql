-- =====================================================================
-- mandi_pipeline schema  (PostgreSQL, "mandi" schema on the shared server)
-- =====================================================================
-- Apply once:  python -m mandi_pipeline.run --init-db
-- or:          psql "$DATABASE_URL" -f mandi_pipeline/db/schema.sql
--
-- The direct-API pipeline writes ONLY to mandi.market_prices_v3 (below).
-- It never touches mandi.market_prices or mandi.market_prices_v2 -- those
-- belong to the existing browser scraper and the QA dashboard. v3 is the
-- parallel-run table the 2026-09-03 investigation recommended, so the API
-- data can be compared against v2 for a full day before any cutover.

CREATE SCHEMA IF NOT EXISTS mandi;

-- ---------------------------------------------------------------------
-- Price rows. Column set mirrors mandi.market_prices_v2 exactly (so a
-- v3-vs-v2 diff is column-for-column), plus provenance columns:
--   source           - which pipeline wrote the row
--   source_row_hash  - sha256 of the business fields; drives modified-row
--                      detection (an upsert only rewrites a row when the
--                      hash changed) and new-vs-updated counting
--   first_seen_at    - when this (unique-key) row first appeared
--   scraped_at       - last time the pipeline confirmed/refreshed it
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS mandi.market_prices_v3 (
    market_price_id  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    state            VARCHAR(120) NOT NULL,
    district         VARCHAR(120) NOT NULL,
    market           VARCHAR(160) NOT NULL,
    commodity_group  VARCHAR(120),
    commodity        VARCHAR(160) NOT NULL,
    variety          VARCHAR(160) NOT NULL DEFAULT '',
    grade            VARCHAR(120) NOT NULL DEFAULT '',
    arrival_date     DATE NOT NULL,
    price_date       DATE,
    -- Nullable on purpose: AGMARKNET routinely reports a modal price with
    -- min/max blank (or vice versa). We store EXACTLY what the site shows --
    -- a blank cell stays NULL, never guessed from the other two -- so the
    -- row is a faithful copy. A row with all three NULL is dropped upstream.
    min_price        NUMERIC(12, 2),
    max_price        NUMERIC(12, 2),
    modal_price      NUMERIC(12, 2),
    price_unit       VARCHAR(40),
    arrival_quantity NUMERIC(14, 2),
    arrival_unit     VARCHAR(40),
    source           VARCHAR(40)  NOT NULL DEFAULT 'agmarknet_api',
    source_row_hash  CHAR(64)     NOT NULL,
    first_seen_at    TIMESTAMP    NOT NULL DEFAULT (now() AT TIME ZONE 'utc'),
    scraped_at       TIMESTAMP    NOT NULL DEFAULT (now() AT TIME ZONE 'utc'),
    -- Postgres treats NULL <> NULL in UNIQUE constraints, so variety/grade
    -- are NOT NULL DEFAULT '' -- otherwise a same-day re-run of a
    -- blank-variety commodity would insert a duplicate instead of updating.
    UNIQUE (state, district, market, commodity, variety, grade, arrival_date)
);

-- Reconcile a market_prices_v3 that already exists as a plain
-- market_prices_v2 clone (no provenance columns). Non-destructive:
-- nullable / defaulted columns. Safe to run repeatedly.
ALTER TABLE mandi.market_prices_v3 ADD COLUMN IF NOT EXISTS source          VARCHAR(40) NOT NULL DEFAULT 'agmarknet_api';
ALTER TABLE mandi.market_prices_v3 ADD COLUMN IF NOT EXISTS source_row_hash CHAR(64);
ALTER TABLE mandi.market_prices_v3 ADD COLUMN IF NOT EXISTS first_seen_at   TIMESTAMP NOT NULL DEFAULT (now() AT TIME ZONE 'utc');
-- a unique key is required for the upsert; add it if the clone lacks it
DO $$ BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint
        WHERE conrelid = 'mandi.market_prices_v3'::regclass AND contype = 'u'
    ) THEN
        ALTER TABLE mandi.market_prices_v3
            ADD CONSTRAINT market_prices_v3_uq
            UNIQUE (state, district, market, commodity, variety, grade, arrival_date);
    END IF;
END $$;
-- Faithful-copy migration: a pre-existing v3 has min/max/modal NOT NULL.
-- Drop it so partial-price rows are stored as the site shows them.
ALTER TABLE mandi.market_prices_v3 ALTER COLUMN min_price   DROP NOT NULL;
ALTER TABLE mandi.market_prices_v3 ALTER COLUMN max_price   DROP NOT NULL;
ALTER TABLE mandi.market_prices_v3 ALTER COLUMN modal_price DROP NOT NULL;

CREATE INDEX IF NOT EXISTS idx_mp_v3_commodity_date
    ON mandi.market_prices_v3 (commodity, arrival_date DESC);
CREATE INDEX IF NOT EXISTS idx_mp_v3_arrival_date
    ON mandi.market_prices_v3 (arrival_date DESC);

-- ---------------------------------------------------------------------
-- One row per pipeline execution -- success OR failure. This is the
-- "maintain the timestamp of every successful and failed API execution"
-- requirement. Query the last N rows for monitoring / alerting.
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS mandi.pipeline_runs (
    run_id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    approach           VARCHAR(20) NOT NULL,               -- 'agmarknet_api' | 'data_gov_in'
    trigger            VARCHAR(20) NOT NULL DEFAULT 'timer',-- 'timer' | 'manual' | 'catchup'
    target_date        DATE,
    started_at         TIMESTAMP NOT NULL DEFAULT (now() AT TIME ZONE 'utc'),
    finished_at        TIMESTAMP,
    status             VARCHAR(20) NOT NULL DEFAULT 'running',
                       -- running | success | partial | failed | aborted | skipped_locked
    commodities_total  INTEGER DEFAULT 0,
    commodities_done   INTEGER DEFAULT 0,
    commodities_failed INTEGER DEFAULT 0,
    rows_seen          INTEGER DEFAULT 0,
    rows_inserted      INTEGER DEFAULT 0,
    rows_updated       INTEGER DEFAULT 0,
    rows_unchanged     INTEGER DEFAULT 0,
    rows_missing       INTEGER DEFAULT 0,   -- declared by the API but never stored
    rows_pruned        INTEGER DEFAULT 0,   -- stale rows deleted to mirror the site
    captcha_solves     INTEGER DEFAULT 0,
    throttle_events    INTEGER DEFAULT 0,
    error              TEXT,
    host               VARCHAR(120)
);

CREATE INDEX IF NOT EXISTS idx_pipeline_runs_started
    ON mandi.pipeline_runs (approach, started_at DESC);

-- ---------------------------------------------------------------------
-- Per-commodity progress for the sweep of one target_date. A 4-hourly
-- re-run reads this and skips commodities already 'done', so each wake
-- makes forward progress / mops up what earlier wakes missed instead of
-- starting the day over. Rows for a fully-finished day can be pruned.
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS mandi.pipeline_progress (
    approach       VARCHAR(20) NOT NULL,
    target_date    DATE        NOT NULL,
    commodity_id   INTEGER     NOT NULL,
    commodity_name VARCHAR(160),
    status         VARCHAR(20) NOT NULL,        -- done | failed | empty
    rows_upserted  INTEGER DEFAULT 0,
    attempts       INTEGER DEFAULT 0,
    updated_at     TIMESTAMP NOT NULL DEFAULT (now() AT TIME ZONE 'utc'),
    last_error     TEXT,
    PRIMARY KEY (approach, target_date, commodity_id)
);

-- ---------------------------------------------------------------------
-- Approach 2 target (v4): rows from the data.gov.in resource. Own table
-- (not v3) so the two pipelines never fight over the same unique key --
-- each is compared against ITS OWN previous snapshot. Same column set as
-- v3 plus stale_at: set when a (unique-key) row was in a previous snapshot
-- but not the latest one ("missing"), cleared when it reappears.
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS mandi.market_prices_v4 (
    market_price_id  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    state            VARCHAR(120) NOT NULL,
    district         VARCHAR(120) NOT NULL,
    market           VARCHAR(160) NOT NULL,
    commodity_group  VARCHAR(120),
    commodity        VARCHAR(160) NOT NULL,
    variety          VARCHAR(160) NOT NULL DEFAULT '',
    grade            VARCHAR(120) NOT NULL DEFAULT '',
    arrival_date     DATE NOT NULL,
    price_date       DATE,
    min_price        NUMERIC(12, 2) NOT NULL,
    max_price        NUMERIC(12, 2) NOT NULL,
    modal_price      NUMERIC(12, 2) NOT NULL,
    price_unit       VARCHAR(40),
    arrival_quantity NUMERIC(14, 2),
    arrival_unit     VARCHAR(40),
    source           VARCHAR(40)  NOT NULL DEFAULT 'data_gov_in',
    source_row_hash  CHAR(64)     NOT NULL,
    first_seen_at    TIMESTAMP    NOT NULL DEFAULT (now() AT TIME ZONE 'utc'),
    scraped_at       TIMESTAMP    NOT NULL DEFAULT (now() AT TIME ZONE 'utc'),
    stale_at         TIMESTAMP,
    UNIQUE (state, district, market, commodity, variety, grade, arrival_date)
);
CREATE INDEX IF NOT EXISTS idx_mp_v4_arrival_date
    ON mandi.market_prices_v4 (arrival_date DESC);
CREATE INDEX IF NOT EXISTS idx_mp_v4_stale
    ON mandi.market_prices_v4 (stale_at) WHERE stale_at IS NOT NULL;

-- Per-approach source watermark: what the last SUCCESSFUL run saw, so a
-- run can skip the (large) insert path when the upstream resource has not
-- changed -- while STILL logging the execution in pipeline_runs.
CREATE TABLE IF NOT EXISTS mandi.pipeline_source_state (
    approach           VARCHAR(20) PRIMARY KEY,
    resource_id        VARCHAR(80),
    upstream_updated   BIGINT,        -- the resource's `updated` epoch
    upstream_updated_at TIMESTAMP,    -- its `updated_date`
    rows_last_seen     INTEGER,
    last_run_id        BIGINT,
    last_success_at    TIMESTAMP
);

ALTER TABLE mandi.pipeline_runs ADD COLUMN IF NOT EXISTS rows_missing INTEGER DEFAULT 0;
ALTER TABLE mandi.pipeline_runs ADD COLUMN IF NOT EXISTS rows_pruned  INTEGER DEFAULT 0;

-- ---------------------------------------------------------------------
-- Cached commodity taxonomy from GET /v1/daily-price-arrival/filters
-- (no CAPTCHA). Refreshed on demand; the pipeline reads it to know which
-- (group_id, commodity_id) pairs to sweep.
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS mandi.agmarknet_taxonomy (
    commodity_id    INTEGER PRIMARY KEY,
    commodity_name  VARCHAR(160) NOT NULL,
    group_id        INTEGER,
    group_name      VARCHAR(160),
    active          BOOLEAN NOT NULL DEFAULT TRUE,
    refreshed_at    TIMESTAMP NOT NULL DEFAULT (now() AT TIME ZONE 'utc')
);

-- ---------------------------------------------------------------------
-- Site-vs-DB comparison results, shown on the dashboard's "Comparison"
-- page. One row per (arrival_date, commodity), overwritten by each new
-- check (verify.py --live/--deep). The live check needs a CAPTCHA per
-- commodity, so it runs from the pipeline CLI and the dashboard only
-- READS what it saved.
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS mandi.record_comparisons (
    comparison_id    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    arrival_date     DATE         NOT NULL,
    commodity        VARCHAR(160) NOT NULL,
    site_declared    INTEGER,
    site_parsed      INTEGER,
    db_rows          INTEGER,
    csv_rows         INTEGER,
    missing_in_db    INTEGER      NOT NULL DEFAULT 0,
    stale_in_db      INTEGER      NOT NULL DEFAULT 0,
    only_in_csv      INTEGER,
    field_diff_count INTEGER,
    in_sync          BOOLEAN      NOT NULL,
    verdict          TEXT         NOT NULL,
    fixed            BOOLEAN      NOT NULL DEFAULT FALSE,
    -- capped samples: missing / stale / only_csv keys and field_diffs
    details          JSONB        NOT NULL DEFAULT '{}'::jsonb,
    checked_at       TIMESTAMP    NOT NULL DEFAULT (now() AT TIME ZONE 'utc'),
    UNIQUE (arrival_date, commodity)
);
CREATE INDEX IF NOT EXISTS idx_rc_date ON mandi.record_comparisons (arrival_date DESC);

-- Audit trail for rows removed from the Duplicates page. The full deleted
-- row is kept as JSON so a deletion can be reviewed / restored by hand.
CREATE TABLE IF NOT EXISTS mandi.duplicate_audit (
    audit_id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kept_id          BIGINT       NOT NULL,
    deleted_id       BIGINT       NOT NULL,
    deleted_row      JSONB        NOT NULL,
    deleted_by       VARCHAR(160) NOT NULL,
    deleted_at       TIMESTAMP    NOT NULL DEFAULT (now() AT TIME ZONE 'utc')
);
