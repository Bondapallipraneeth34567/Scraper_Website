"""Fixes the column ORDER of mandi.market_prices and mandi.market_prices_v2
to exactly match what was actually requested (state/ut, district, market,
commodity group, commodity, variety, grade, min price, max price, modal
price, price unit, price date, arrival quantity, arrival unit, arrival
date) -- the previous migration got the right columns onto the table but
appended the new ones at the end instead of interleaving them into that
order, which Postgres's ALTER TABLE ADD COLUMN always does (there's no
ALTER TABLE ... POSITION in Postgres) and a plain ALTER RENAME COLUMN
can't fix either -- reordering physical column position requires
rebuilding the table.

Also drops crop_keyword entirely (not part of the requested list, and no
longer needed as a column now that the upsert/dedup key is
(state, district, market, commodity, arrival_date) instead -- see the
same 2026-08-31 update to both scrapers' _UPSERT_SQL. market is IN the
key, not just state/district/commodity -- confirmed live that a district
commonly has several markets all reporting the same commodity the same
day, and a key without market would silently collapse them down to one,
discarding every other market's real, distinct price data).
market_price_id (PK) isn't part of the requested list either but stays,
as the one remaining internal-only column, at the very start.

mandi.verification_results has a FOREIGN KEY on market_price_id ->
mandi.market_prices(market_price_id) (1 row today) -- renaming a table
does NOT move an existing FK to "whatever now has this name", it stays
bound to the original table's OID. So this drops and recreates that FK
explicitly against the rebuilt table, rather than silently leaving
verification_results pointing at an orphaned old copy.

Verifies row counts before dropping anything, and never touches
mandi.market_prices_backup_20260831 (kept as the earlier, pre-any-
migration snapshot -- that backup still has crop_keyword, as a full
record of the table's state before either change).
"""
import asyncio

import asyncpg
from config import settings

# (schema_name_of_target, has_verification_fk)
TABLES = [("market_prices", True), ("market_prices_v2", False)]

CREATE_TMPL = """
CREATE TABLE mandi.{table}_reordered (
    market_price_id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    state                 TEXT NOT NULL,
    district              TEXT NOT NULL,
    market                TEXT NOT NULL,
    commodity_group       TEXT,
    commodity             TEXT NOT NULL,
    variety               TEXT,
    grade                 TEXT,
    min_price             NUMERIC NOT NULL,
    max_price             NUMERIC NOT NULL,
    modal_price           NUMERIC NOT NULL,
    price_unit            TEXT,
    price_date            DATE,
    arrival_quantity      NUMERIC,
    arrival_unit          TEXT,
    arrival_date          DATE NOT NULL,
    scraped_at            TIMESTAMP NOT NULL DEFAULT (now() AT TIME ZONE 'utc'),
    CONSTRAINT uq_{table}_reordered_upsert_key UNIQUE (state, district, market, commodity, arrival_date)
);
"""
# Postgres index/constraint names are unique per-SCHEMA, not per-table --
# the _reordered table has to exist alongside the still-live original
# table for a moment (before the drop+rename swap), so its constraint
# needs a temporarily different name to avoid colliding with the
# original's uq_{table}_upsert_key. Renamed back to the clean name once
# the swap is done and the original (and its same-named constraint) is
# gone -- confirmed live (first attempt) that skipping this causes
# asyncpg.exceptions.DuplicateTableError before anything else runs, with
# nothing touched yet.
RENAME_CONSTRAINT_TMPL = (
    "ALTER TABLE mandi.{table} RENAME CONSTRAINT "
    "uq_{table}_reordered_upsert_key TO uq_{table}_upsert_key;"
)

COPY_TMPL = """
INSERT INTO mandi.{table}_reordered
    (market_price_id, state, district, market, commodity_group, commodity,
     variety, grade, min_price, max_price, modal_price, price_unit,
     price_date, arrival_quantity, arrival_unit, arrival_date, scraped_at)
SELECT market_price_id, state, district, market, commodity_group, commodity,
       variety, grade, min_price, max_price, modal_price, price_unit,
       price_date, arrival_quantity, arrival_unit, arrival_date, scraped_at
FROM mandi.{table};
"""

INDEX_TMPL = [
    "CREATE INDEX idx_{table}_state ON mandi.{table} (state);",
    "CREATE INDEX idx_{table}_district ON mandi.{table} (district);",
    "CREATE INDEX idx_{table}_market ON mandi.{table} (market);",
    "CREATE INDEX idx_{table}_commodity ON mandi.{table} (commodity);",
    "CREATE INDEX idx_{table}_arrival_date ON mandi.{table} (arrival_date);",
]


async def reorder(conn: asyncpg.Connection, table: str, has_fk: bool) -> None:
    print(f"\n=== {table} ===")
    before = await conn.fetchval(f"SELECT COUNT(*) FROM mandi.{table}")
    print(f"rows before: {before}")

    await conn.execute(f"DROP TABLE IF EXISTS mandi.{table}_reordered;")
    await conn.execute(CREATE_TMPL.format(table=table))
    await conn.execute(COPY_TMPL.format(table=table))

    after = await conn.fetchval(f"SELECT COUNT(*) FROM mandi.{table}_reordered")
    print(f"rows copied: {after}")
    if after != before:
        raise RuntimeError(f"Row count mismatch for {table}: {before} -> {after}, aborting before touching the original table")

    max_id = await conn.fetchval(f"SELECT COALESCE(MAX(market_price_id), 0) FROM mandi.{table}_reordered")
    await conn.execute(
        f"SELECT setval(pg_get_serial_sequence('mandi.{table}_reordered', 'market_price_id'), $1)",
        max_id,
    )

    # Everything from here on swaps the live table's identity -- wrapped in
    # one transaction so a concurrent writer (the scraper is actively
    # upserting into market_prices right now) never sees a moment where
    # the table doesn't exist between DROP and RENAME. Postgres DDL is
    # transactional, so this is a real all-or-nothing swap, not just
    # "less likely to race."
    async with conn.transaction():
        if has_fk:
            await conn.execute("ALTER TABLE mandi.verification_results DROP CONSTRAINT verification_results_market_price_id_fkey;")
            print("dropped verification_results' FK (will recreate against the rebuilt table)")

        await conn.execute(f"DROP TABLE mandi.{table};")
        await conn.execute(f"ALTER TABLE mandi.{table}_reordered RENAME TO {table};")
        await conn.execute(RENAME_CONSTRAINT_TMPL.format(table=table))
        print(f"mandi.{table} rebuilt with correct column order")

        for stmt in INDEX_TMPL:
            await conn.execute(stmt.format(table=table))
        print("indexes recreated")

        if has_fk:
            await conn.execute(
                "ALTER TABLE mandi.verification_results "
                "ADD CONSTRAINT verification_results_market_price_id_fkey "
                "FOREIGN KEY (market_price_id) REFERENCES mandi.market_prices(market_price_id);"
            )
            print("recreated verification_results' FK against the rebuilt table")

    final_count = await conn.fetchval(f"SELECT COUNT(*) FROM mandi.{table}")
    cols = await conn.fetch(
        "SELECT column_name FROM information_schema.columns WHERE table_schema='mandi' AND table_name=$1 ORDER BY ordinal_position",
        table,
    )
    print(f"final row count: {final_count}")
    print("final column order:", [c["column_name"] for c in cols])


async def main() -> None:
    conn = await asyncpg.connect(
        host=settings.host, port=settings.port, user=settings.user,
        password=settings.password, database=settings.database,
        ssl="require" if settings.ssl else None,
    )
    try:
        for table, has_fk in TABLES:
            await reorder(conn, table, has_fk)
    finally:
        await conn.close()


if __name__ == "__main__":
    asyncio.run(main())
